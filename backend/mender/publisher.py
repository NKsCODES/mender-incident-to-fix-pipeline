"""Turns a verified patch into a reviewable PR. Local branch always; GitHub only when MENDER_PUBLISH=1."""
from __future__ import annotations

import subprocess

from mender.sandbox import Sandbox


def pr_body(run: dict, agent_text: str, verification: dict, violations: list[dict], dashboard_url: str = "") -> str:
    inc = run["incident"]
    exc = inc["exception"]
    warn = "\n".join(f"- {v['rule']}: {v['detail']}" for v in violations) or "- none"
    return f"""## Incident
`{exc['type']}: {exc.get('value', '')}` in **{inc['service']}** ({inc.get('environment', 'unknown')}), seen {run.get('occurrences', 1)} time(s).

## Agent summary
{agent_text.strip() or 'No summary returned.'}

## Evidence
- New regression test: {', '.join(verification.get('new_tests') or ['none'])}
- Fails before the fix: {verification.get('repro')}
- Full suite after the fix: {'passed' if verification.get('suite_passed') else 'FAILED'}
- Agent attempts: {run.get('attempts')}

## Guardrail notes
{warn}

Generated by Mender run `{run['id']}`. {dashboard_url}
"""


def publish(sb: Sandbox, run: dict, body: str, draft: bool, push: bool) -> dict:
    branch = f"mender/{run['id']}"
    sb.commit_branch(branch, f"fix: {run['title'][:60]}\n\nMender run {run['id']}")
    out = {"branch": branch, "pr_url": None}
    if push and sb.svc.github_repo:
        sb._git(["push", "-q", "origin", branch])
        cmd = ["gh", "pr", "create", "--repo", sb.svc.github_repo, "--head", branch, "--title", f"fix: {run['title'][:60]}", "--body", body]
        if draft:
            cmd.append("--draft")
        p = subprocess.run(cmd, cwd=sb.dir, capture_output=True, text=True)
        if p.returncode != 0:
            raise RuntimeError(f"gh pr create failed: {p.stderr.strip()[:300]}")
        out["pr_url"] = p.stdout.strip().splitlines()[-1]
    return out
